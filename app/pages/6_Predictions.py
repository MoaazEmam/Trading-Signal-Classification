from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import requests
import streamlit as st

from src.config import settings

ROOT = Path(__file__).resolve().parent.parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

st.set_page_config(page_title="Daily Predictions", layout="wide")

API_BASE = settings.api_url

CLASS_COLORS = {"Buy": "#2ca02c", "Hold": "#7f7f7f", "Sell": "#d62728"}


# ── helpers ──────────────────────────────────────────────────────────────────


@st.cache_data(ttl=300)
def _fetch_latest() -> dict:
    r = requests.get(f"{API_BASE}/predictions/latest", timeout=10)
    r.raise_for_status()
    return r.json()


@st.cache_data(ttl=3600)
def _fetch_dates() -> list[str]:
    r = requests.get(f"{API_BASE}/predictions/dates", timeout=10)
    r.raise_for_status()
    return r.json()["dates"]


@st.cache_data(ttl=3600)
def _fetch_by_date(date: str) -> dict:
    r = requests.get(f"{API_BASE}/predictions/history/{date}", timeout=10)
    r.raise_for_status()
    return r.json()


def _to_df(payload: dict) -> pd.DataFrame:
    return pd.DataFrame(payload["predictions"])


st.title("Daily Trading Signals")
st.caption(
    "Buy / Hold / Sell predictions generated by the trained model. "
    "Predictions run automatically at 1 AM EET on every trading day."
)

# date selector
st.sidebar.header("Date")
view_mode = st.sidebar.radio("View", ["Latest", "Historical"])

if view_mode == "Latest":
    try:
        payload = _fetch_latest()
    except Exception as e:
        st.error(f"Could not reach API at {API_BASE}: {e}")
        st.stop()
    df = _to_df(payload)
    date_label = payload["date"]
    source_label = payload["source"]
else:
    try:
        dates = _fetch_dates()
    except Exception as e:
        st.error(f"Could not reach API at {API_BASE}: {e}")
        st.stop()

    if not dates:
        st.warning("No archived predictions available.")
        st.stop()

    selected_date = st.sidebar.selectbox("Select date", dates)
    try:
        payload = _fetch_by_date(selected_date)
    except Exception as e:
        st.error(f"Failed to load predictions for {selected_date}: {e}")
        st.stop()
    df = _to_df(payload)
    date_label = selected_date
    source_label = "archive"


st.subheader(f"Predictions for {date_label}")
if source_label == "archive":
    st.caption("⚠️ Showing archived predictions (latest not available).")

counts = df["predicted_label"].value_counts()
col1, col2, col3, col4 = st.columns(4)
col1.metric("Total signals", len(df))
col2.metric("Buy", counts.get("Buy", 0), delta=None)
col3.metric("Hold", counts.get("Hold", 0), delta=None)
col4.metric("Sell", counts.get("Sell", 0), delta=None)


st.divider()
col_chart, col_pie = st.columns(2)

with col_chart:
    st.subheader("Signal distribution")
    dist_df = counts.reset_index()
    dist_df.columns = ["Signal", "Count"]
    dist_df["Color"] = dist_df["Signal"].map(CLASS_COLORS)
    fig_bar = px.bar(
        dist_df,
        x="Signal",
        y="Count",
        color="Signal",
        color_discrete_map=CLASS_COLORS,
        text="Count",
    )
    fig_bar.update_traces(textposition="outside")
    fig_bar.update_layout(showlegend=False, height=350)
    st.plotly_chart(fig_bar, use_container_width=True)

with col_pie:
    st.subheader("Signal share")
    fig_pie = px.pie(
        dist_df,
        names="Signal",
        values="Count",
        color="Signal",
        color_discrete_map=CLASS_COLORS,
        hole=0.4,
    )
    fig_pie.update_layout(height=350)
    st.plotly_chart(fig_pie, use_container_width=True)


st.divider()
st.subheader("Probability breakdown by signal")
st.caption(
    "Average model confidence per signal class. "
    "Low separation between Buy and Sell probabilities indicates uncertainty."
)

proba_cols = [c for c in df.columns if c.startswith("proba_")]
if proba_cols:
    avg_proba = df.groupby("predicted_label")[proba_cols].mean().reset_index()
    fig_proba = go.Figure()
    for col in proba_cols:
        label = col.replace("proba_", "").capitalize()
        fig_proba.add_trace(
            go.Bar(
                name=label,
                x=avg_proba["predicted_label"],
                y=avg_proba[col],
                marker_color=CLASS_COLORS.get(label, None),
            )
        )
    fig_proba.update_layout(
        barmode="group",
        xaxis_title="Predicted signal",
        yaxis_title="Average probability",
        height=350,
        yaxis_tickformat=".0%",
    )
    st.plotly_chart(fig_proba, use_container_width=True)


st.divider()
st.subheader("All signals")

label_filter = st.multiselect(
    "Filter by signal",
    options=["Buy", "Hold", "Sell"],
    default=["Buy", "Sell"],
)
filtered = df[df["predicted_label"].isin(label_filter)] if label_filter else df

search = st.text_input("Search ticker", "")
if search:
    filtered = filtered[filtered["Company"].str.upper().str.contains(search.upper())]

st.dataframe(
    filtered.sort_values("predicted_label").reset_index(drop=True),
    use_container_width=True,
    height=400,
)

st.caption(f"Showing {len(filtered)} of {len(df)} companies.")
